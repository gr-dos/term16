#!/usr/bin/env python3
"""Write src/cp437.c: Unicode to code page 437, from Python's cp437 codec
plus the glyphs of bytes 01h-1Fh and 7Fh and a few look-alikes."""
import sys

pairs = {}
for b in range(0x80, 0x100):
    pairs[ord(bytes([b]).decode('cp437'))] = b
# The glyphs the display shows for the control bytes
low = "☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
for i, ch in enumerate(low, 1):
    pairs.setdefault(ord(ch), i)
pairs.setdefault(ord('⌂'), 0x7F)
# Near matches CP437 lacks
alias = {
    '‘': "'", '’': "'", '‚': ',', '“': '"', '”': '"', '„': '"',
    '–': '-', '—': '-', '―': '-', '−': '-', '…': '.', '′': "'", '″': '"',
    '‹': '<', '›': '>', '€': 'E', '™': 'T', '©': 'c', '®': 'R',
    '×': 'x', '•': '\x07', '◆': '\x04', '✓': '\xfb', '✔': '\xfb',
    '╭': '┌', '╮': '┐', '╯': '┘', '╰': '└',
    '━': '═', '┃': '║', '┏': '╔', '┓': '╗', '┗': '╚', '┛': '╝',
    '┣': '╠', '┫': '╣', '┳': '╦', '┻': '╩', '╋': '╬',
    '╴': '─', '╶': '─', '╵': '│', '╷': '│', '┄': '─', '┈': '─',
    '┆': '│', '┊': '│', '╌': '─', '╎': '│',
    '▁': '▄', '▂': '▄', '▃': '▄', '▅': '▄', '▆': '▄', '▇': '█',
    '▉': '█', '▊': '▌', '▋': '▌', '▍': '▌', '▎': '▌', '▏': '▌',
    '▕': '▐', '▔': '▀', '⏎': '\x11', '←': '\x1b', '→': '\x1a',
    '↑': '\x18', '↓': '\x19', '¦': '|', ' ': '\xff',
}
for k, v in alias.items():
    if ord(k) in pairs:
        continue
    t = v.encode('cp437')[0] if ord(v) >= 0x80 and ord(v) < 0x100 and v not in '\xfb\xff' else None
    if v in ('\xfb', '\xff'):
        t = ord(v)
    elif t is None:
        t = pairs.get(ord(v), ord(v)) if len(v) == 1 else None
    pairs[ord(k)] = t

items = sorted(pairs.items())
assert all(u < 0x10000 for u, _ in items)
out = sys.stdout
out.write('/*\n * cp437.c - Unicode to code page 437 (generated by tools/gen-cp437.py)\n *\n'
          ' * Portable C: also built on the host for tests/unit.\n */\n\n'
          '#include "term16.h"\n\n')
out.write('static const unsigned short ucs[%d] = {\n' % len(items))
for i in range(0, len(items), 8):
    out.write('    ' + ', '.join('0x%04X' % u for u, _ in items[i:i+8]) + ',\n')
out.write('};\n\nstatic const unsigned char cp[%d] = {\n' % len(items))
for i in range(0, len(items), 12):
    out.write('    ' + ', '.join('0x%02X' % c for _, c in items[i:i+12]) + ',\n')
out.write('};\n\n')
out.write('''/* The code page 437 byte for a Unicode character, or -1 */
int cp437_from_ucs(unsigned long u)
{
    int lo = 0, hi = (int)(sizeof ucs / sizeof ucs[0]) - 1;

    if (u < 0x80)
        return (int)u;
    if (u > 0xFFFF)
        return -1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;

        if (ucs[mid] == u)
            return cp[mid];
        if (ucs[mid] < u)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return -1;
}
''')
